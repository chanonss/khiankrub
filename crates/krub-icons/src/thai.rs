//! Approved square Thai Distribution symbol. The ท outline is derived from Sarabun
//! SemiBold (SIL OFL 1.1); see OFL-Sarabun.txt and ATTRIBUTION.md. Geometry is
//! preflattened on a 24-unit master so rendering never depends on installed fonts.

use egui::{Color32, Painter, Rect, Shape, Stroke, StrokeKind, vec2};

pub(crate) fn paint(p: &Painter, rect: Rect, ink: Color32, flat: bool) {
    let size = rect.width().min(rect.height());
    if !size.is_finite() || size <= 0.5 || !rect.center().is_finite() {
        return;
    }
    let scale = size / 24.0;
    let origin = rect.center() - vec2(size * 0.5, size * 0.5);
    let point = |x, y| origin + vec2(x, y) * scale;
    let square = Rect::from_min_max(point(3.0, 3.0), point(21.0, 21.0));
    let fill = if flat { Color32::TRANSPARENT } else { crate::gold(ink, crate::GoldRole::Surface, 1.0) };
    p.rect_filled(square, 1.1 * scale, fill);
    p.rect_stroke(square, 1.1 * scale, Stroke::new((1.35 * scale).max(0.85), ink), StrokeKind::Middle);
    let mut mesh = egui::epaint::Mesh::default();
    for &(lx0, rx0, y0, lx1, rx1, y1) in GLYPH_BANDS {
        let start = mesh.vertices.len() as u32;
        for position in [point(lx0, y0), point(rx0, y0), point(rx1, y1), point(lx1, y1)] {
            mesh.colored_vertex(position, ink);
        }
        mesh.add_triangle(start, start + 1, start + 2);
        mesh.add_triangle(start, start + 2, start + 3);
    }
    p.add(Shape::mesh(mesh));
    // Anti-alias only the real contours, including the loop counter, without stroking internal band edges.
    for contour in [OUTER, INNER] {
        p.add(Shape::closed_line(contour.iter().map(|&(x, y)| point(x, y)).collect(), Stroke::new(0.2 * scale, ink)));
    }
}

