//! One-off generator (not part of the product): prints the Rust constants for the Thai Digits
//! icon's ๒, outlined from Sarabun SemiBold (SIL OFL 1.1) on the same 24-unit master as the
//! Thai Distribution ท: `cargo run -p wordcraft-fonts --example gen_thai_digit_icon -- Sarabun-SemiBold.ttf`
use kurbo::{BezPath, PathEl, Point};
use skrifa::instance::{LocationRef, Size};
use skrifa::outline::{DrawSettings, OutlinePen};
use skrifa::{FontRef, MetadataProvider};

struct Pen(BezPath);
impl OutlinePen for Pen {
    fn move_to(&mut self, x: f32, y: f32) {
        self.0.move_to((x as f64, y as f64));
    }
    fn line_to(&mut self, x: f32, y: f32) {
        self.0.line_to((x as f64, y as f64));
    }
    fn quad_to(&mut self, cx: f32, cy: f32, x: f32, y: f32) {
        self.0.quad_to((cx as f64, cy as f64), (x as f64, y as f64));
    }
    fn curve_to(&mut self, a: f32, b: f32, c: f32, d: f32, x: f32, y: f32) {
        self.0.curve_to((a as f64, b as f64), (c as f64, d as f64), (x as f64, y as f64));
    }
    fn close(&mut self) {
        self.0.close_path();
    }
}

fn main() {
    let path = std::env::args().nth(1).expect("font path");
    let data = std::fs::read(path).expect("read font");
    let font = FontRef::new(&data).expect("font");
    let ch = std::env::args().nth(2).and_then(|s| s.chars().next()).unwrap_or('\u{0E52}');
    let gid = font.charmap().map(ch).expect("glyph");
    let mut pen = Pen(BezPath::new());
    font.outline_glyphs().get(gid).expect("outline").draw(DrawSettings::unhinted(Size::unscaled(), LocationRef::default()), &mut pen).expect("draw");
    // Flatten into closed polylines (font units, y up).
    let mut contours: Vec<Vec<Point>> = Vec::new();
    let mut cur: Vec<Point> = Vec::new();
    kurbo::flatten(pen.0.iter(), 0.4, |el| match el {
        PathEl::MoveTo(p) => {
            if cur.len() > 2 {
                contours.push(std::mem::take(&mut cur));
            }
            cur = vec![p];
        }
        PathEl::LineTo(p) => cur.push(p),
        PathEl::ClosePath if cur.len() > 2 => contours.push(std::mem::take(&mut cur)),
        _ => {}
    });
    if cur.len() > 2 {
        contours.push(cur);
    }
    let (mut x0, mut x1, mut y0, mut y1) = (f64::MAX, f64::MIN, f64::MAX, f64::MIN);
    for p in contours.iter().flatten() {
        x0 = x0.min(p.x);
        x1 = x1.max(p.x);
        y0 = y0.min(p.y);
        y1 = y1.max(p.y);
    }
    // Fit a 11.78-unit box centred at (12, 12), like the ท (6.1..17.9).
    let side = 11.78;
    let k = side / (x1 - x0).max(y1 - y0);
    let (cx, cy) = ((x0 + x1) / 2.0, (y0 + y1) / 2.0);
    let to24 = |p: Point| ((12.0 + (p.x - cx) * k) as f32, (12.0 - (p.y - cy) * k) as f32);
    let polys: Vec<Vec<(f32, f32)>> = contours.iter().map(|c| c.iter().map(|p| to24(*p)).collect()).collect();
    let (top, bottom) = ((12.0 - (y1 - y0) * k / 2.0) as f32, (12.0 + (y1 - y0) * k / 2.0) as f32);
    // Scanline bands: the filled intervals (non-zero winding) at each slice's middle.
    let rows = 150;
    println!("// Generated by crates/fonts/examples/gen_thai_digit_icon.rs from Sarabun SemiBold (SIL OFL 1.1).");
    println!("const DIGIT_BANDS: &[(f32, f32, f32, f32, f32, f32)] = &[");
    for r in 0..rows {
        let ya = top + (bottom - top) * r as f32 / rows as f32;
        let yb = top + (bottom - top) * (r + 1) as f32 / rows as f32;
        let ym = (ya + yb) / 2.0;
        let mut xs: Vec<(f32, i32)> = Vec::new();
        for poly in &polys {
            for w in 0..poly.len() {
                let (a, b) = (poly[w], poly[(w + 1) % poly.len()]);
                if (a.1 <= ym) != (b.1 <= ym) {
                    let t = (ym - a.1) / (b.1 - a.1);
                    xs.push((a.0 + t * (b.0 - a.0), if b.1 > a.1 { 1 } else { -1 }));
                }
            }
        }
        xs.sort_by(|p, q| p.0.total_cmp(&q.0));
        let mut wind = 0;
        let mut start = 0.0;
        for (x, d) in xs {
            let before = wind;
            wind += d;
            if before == 0 && wind != 0 {
                start = x;
            } else if before != 0 && wind == 0 && x - start > 0.001 {
                println!("    ({start:.4}, {x:.4}, {ya:.4}, {start:.4}, {x:.4}, {yb:.4}),");
            }
        }
    }
    println!("];");
    println!("const DIGIT_CONTOURS: &[&[(f32, f32)]] = &[");
    for poly in &polys {
        let pts: Vec<String> = poly.iter().map(|p| format!("({:.3}, {:.3})", p.0, p.1)).collect();
        println!("    &[{}],", pts.join(", "));
    }
    println!("];");
}
